def merge(base: Dict[str, Any], over: Dict[str, Any]) -> Dict[str, Any]:
    """`over` on top of `base`: tables merge key by key, anything else is replaced."""
    out = deepcopy(base)
    for k, v in (over or {}).items():
        out[k] = merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else deepcopy(v)
    return out


def parse(text: str, name: str) -> Dict[str, Any]:
    if not text.strip():
        return {}
    if name.endswith(".json"):
        return json.loads(text)
    data = tomllib.loads(text)
    return data.get("tool", {}).get("system-diff", {}) if name.endswith("pyproject.toml") else data


def load(source=None, root: Optional[Path] = None, path: Optional[str] = None) -> Dict[str, Any]:
    """The project's settings over the defaults. `source` is what is being read (a commit or a directory): its own
    system-diff.toml wins over the one on disk, so an old commit is described by the file it had."""
    if path:
        p = Path(path)
        return merge(DEFAULTS, parse(p.read_text(encoding="utf-8"), p.name))
    for name in (FILE, "pyproject.toml"):
        text = source.read(name) if source is not None and name in source.files else ""
        if not text and root is not None and (root / name).is_file():
            text = (root / name).read_text(encoding="utf-8")
        got = parse(text, name) if text else {}
        if got:
            return merge(DEFAULTS, got)
    return deepcopy(DEFAULTS)


def lenient(root: Path) -> Dict[str, Any]:
    """The project's settings, or the defaults when its config does not parse: a hook or a status line must never
    fail on a typo (each part is then named by its folder)."""
    try:
        return load(root=root)
    except ValueError:
        return load()


def segment_rx(names: Iterable[str]) -> re.Pattern:
    """A path containing a directory named like one of `names` (`*` within a name)."""
    alts = "|".join(re.escape(n).replace(r"\*", "[^/]*") for n in names)
    return re.compile(rf"(^|/)({alts})(/|$)") if alts else re.compile(r"(?!)")
